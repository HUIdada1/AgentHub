// KukuAI 协议层的排障日志：只在显式打开调试开关（环境变量 KUKU_DEBUG=1）时输出到控制台。
//
// 不进操作日志的理由与 CatPaw 同款：这里都是协议内部节点（容错跳失败、流内错误、令牌换发结果），
// 每轮对话若干条，进用户可见日志只会刷屏；排障时打开开关即可拿到等价信息。
// 口径：只打元数据与上游文案，**不落 prompt 正文与会话材料**。
"use strict";

function enabled() {
  const v = process.env.KUKU_DEBUG;
  return !!v && v !== "0" && v !== "false";
}

function verbose(message) {
  if (!enabled()) return;
  try {
    console.log(`[Kuku] ${message}`);
  } catch {
    /* 控制台不可用（打包后无 stdout）时静默 */
  }
}

module.exports = { verbose, enabled };

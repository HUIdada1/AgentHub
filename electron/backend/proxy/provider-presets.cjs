/** 校验集合：kind 必须落在 provider.cjs 的 KINDS 里，auth 只认这三档 */
const KINDS = new Set(["openai_compat", "anthropic_messages", "openai_responses"]);
const AUTHS = new Set(["", "bearer", "x-api-key"]);

const SLUG_RE = /^[a-z0-9][a-z0-9_-]{1,31}$/;

/** 目录自检：返回问题清单（空数组 = 干净）。只在启动与自测里跑，不参与请求路径。
 *  为什么要有：这份表是手写数据，任何一条 id 写错、模型名带斜杠、基址重复，
 *  表现都不是报错而是「点了预设却建不出提供商」或「建出来了请求 404」。 */
function audit() {
  const problems = [];
  const ids = new Set();
  const bases = new Map();
  for (const p of PRESETS) {
    if (!SLUG_RE.test(p.id)) problems.push(`${p.id}: 标识不合规`);
    if (ids.has(p.id)) problems.push(`${p.id}: 标识重复`);
    ids.add(p.id);
    if (!KINDS.has(p.kind)) problems.push(`${p.id}: 协议形态 ${p.kind} 不在 KINDS 内`);
    if (!AUTHS.has(p.auth)) problems.push(`${p.id}: 鉴权方式 ${p.auth} 不合法`);
    if (!/^https:\/\//.test(p.baseUrl || "")) problems.push(`${p.id}: 基址必须是 https`);
    const key = `${p.kind}|${p.baseUrl}`;
    if (bases.has(key)) problems.push(`${p.id}: 与 ${bases.get(key)} 同协议同基址`);
    bases.set(key, p.id);
    const seen = new Set();
    for (const m of p.models) {
      const name = typeof m === "string" ? m : m.model;
      if (!name) { problems.push(`${p.id}: 有空模型名`); continue; }
      if (String(name).includes("/")) problems.push(`${p.id}/${name}: 模型名含 /（应拆到 upstream）`);
      if (seen.has(name.toLowerCase())) problems.push(`${p.id}/${name}: 模型名重复`);
      seen.add(name.toLowerCase());
    }
  }
  return problems;
}

/** 管理面精简视图：模型清单留在主进程，创建时按 preset 补全，避免每次刷新列表都传 300+ 条模型 */
function list() {
  return PRESETS.map((p) => ({
    id: p.id,
    display: p.display,
    brand: p.brand,
    group: p.group,
    kind: p.kind,
    baseUrl: p.baseUrl,
    auth: p.auth,
    apiKeyUrl: p.apiKeyUrl || "",
    note: p.note || "",
    modelCount: p.models.length,
  }));
}

function get(id) {
  const key = String(id || "").trim();
  if (!key) return null;
  return PRESETS.find((p) => p.id === key) || null;
}

/** 创建时按预设补全：只给「用户没显式给」的字段补，用户填的一律优先。
 *  id 不在这里定——它是路由前缀，必须由调用方（provider.create）走 SLUG_RE 与冲突校验。
 *
 *  【maxOutputTokens 必须落在模型行上】Anthropic 协议必填 max_tokens，而执行链路只拿得到
 *  「这一行的模型条目」（executor 传给适配器的是 provider 行，没有预设 id，也没有单独的
 *  defaultMaxTokens 字段）。所以预设的兜底值在这里就写进每个模型条目——否则不传 max_tokens
 *  的客户端会退到 8192，长回答被硬截断成 MAX_TOKENS。模型行上已有值时不覆盖。 */
function fill(preset, input) {
  const p = get(preset);
  if (!p) return null;
  const src = input && typeof input === "object" ? input : {};
  const seeded = p.models.map((m) => {
    const entry = typeof m === "string" ? { model: m } : { ...m };
    if (p.defaultMaxTokens && !entry.maxOutputTokens) entry.maxOutputTokens = p.defaultMaxTokens;
    return entry;
  });
  return {
    id: src.id || p.id,
    display: src.display || p.display,
    kind: src.kind || p.kind,
    baseUrl: src.baseUrl || p.baseUrl,
    auth: src.auth != null ? src.auth : p.auth,
    models: Array.isArray(src.models) && src.models.length ? src.models : seeded,
  };
}

module.exports = { PRESETS, KINDS: [...KINDS], AUTHS: [...AUTHS], list, get, fill, audit };

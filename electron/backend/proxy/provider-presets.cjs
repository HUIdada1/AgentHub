// 本地网关 · 自定义提供商的预设目录（单一真源）
//
// 这一层只放「数据 + 纯归一」，不发请求、不碰数据库：网关的规矩仍归 provider.cjs，
// 落库仍归 store.cjs。预设的全部意义是「把用户手抄三件事（地址 / 协议 / 模型清单）变成一次点击」，
// 所以它必须是可编辑的初值，而不是锁死的配置——用户改完地址后，预设不再参与任何判断。
//
// 【数据来源与核验日】渠道清单、上游基址、协议形态取自参考项目 ZCode 的
//   config/provider/zcode-builtin.json（其维护文档标注核验日 2026-10-15，每条附官方文档链接）；
//   「基元律动 / TokenRhythm」取自公开资料（https://tokenrhythm.studio/v1，OpenAI Chat 形态），
//   模型清单不预置，首次用「从上游拉取」获取。
//   模型清单是**快照**：厂商上新不会自动同步，刷新路径是界面上的「从上游拉取」。
//
// 【模型名的拆分规则】网关拒绝含 "/" 的模型名（斜杠是 provider/model 的分隔符），
//   而 OpenRouter(70) / 硅基流动(3) 的模型 id 天然带厂商前缀，故拆成
//     model    = 末段，客户端用它发请求
//     upstream = 完整 id，真正发给上游的名字
//   末段在同一条预设内无重名（生成时已核，0 冲突），否则会静默丢条目。
//
// 【defaultMaxTokens】只作 Anthropic 协议的 max_tokens 兜底：Anthropic 协议必填该字段，
//   而不传 max_tokens 的客户端（WorkBuddy 就是）若被写死成 8192，长回答会被硬截断成
//   「响应因达到最大 token 限制而被截断」。这里的数值是**配置基线**，不是厂商公布的最大值，
//   模型行上仍可逐条改。

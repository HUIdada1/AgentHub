"use strict";
const assert = require("node:assert/strict");
const { createAccountExecution } = require("../electron/backend/extensions/account-execution.cjs");
const { validateAccountExecutionEpoch } = require("../electron/backend/extensions/provider-protocol.cjs");
const fences = createAccountExecution({ maxEntries: 2 });
let cancelled = 0;
const first = fences.acquire("one", () => { cancelled++; first.release(); });
const also = fences.acquire("one", () => { cancelled++; also.release(); });
assert.equal(first.epoch, also.epoch);
const other = fences.acquire("two", () => {});
assert.throws(() => fences.acquire("three", () => {}), /unavailable/);
assert.equal(fences.size, 2); assert.equal(fences.active, 3);
fences.invalidateAccountExecution("one");
assert.equal(cancelled, 2, "all holders are cancelled synchronously before returning");
assert.throws(() => first.assertCurrent()); assert.throws(() => also.assertCurrent());
other.assertCurrent();
const enabled = fences.acquire("one", () => {});
assert.notEqual(enabled.epoch, first.epoch, "disable/re-enable cannot restore old fence");
enabled.release();
const third = fences.acquire("three", () => {});
assert.equal(fences.size, 2);
third.release(); other.release();
const recreated = fences.acquire("one", () => {});
assert.notEqual(recreated.epoch, enabled.epoch, "LRU readmission never starts from a reset counter");
recreated.release(); recreated.release();
for (let i = 0; i < 5000; i++) fences.invalidateAccountExecution("unused-" + i);
assert.equal(fences.size, 2, "management-only invalidations create no tombstones");
validateAccountExecutionEpoch(recreated.epoch);
for (const invalid of [undefined, "", "a".repeat(31), "a".repeat(33), "A".repeat(32), "a".repeat(32) + "\n", 1]) {
  assert.throws(() => validateAccountExecutionEpoch(invalid));
}
let breakRandom = false, stopped = 0;
const broken = createAccountExecution({ random: () => { if (breakRandom) throw new Error("random unavailable"); return "1".repeat(32); } });
const held = broken.acquire("a", () => { stopped++; });
breakRandom = true;
assert.throws(() => broken.invalidateAccountExecution("a"));
assert.equal(broken.failed, true); assert.equal(stopped, 1);
assert.throws(() => held.assertCurrent()); assert.throws(() => broken.acquire("b", () => {}));
held.release();
const failedCancel = createAccountExecution();
const bad = failedCancel.acquire("bad", () => { throw new Error("callback failed"); });
const good = failedCancel.acquire("good", () => { stopped++; });
assert.throws(() => failedCancel.invalidateAccountExecution("bad"));
assert.equal(failedCancel.failed, true); assert.throws(() => good.assertCurrent());
assert.equal(stopped, 2, "one broken cleanup still locks and cancels unrelated holders");
bad.release(); good.release();
assert.equal(fences.active, 0); assert.equal(broken.active, 0); assert.equal(failedCancel.active, 0);
console.log("PASS bounded account execution epochs: synchronous invalidation, isolation, disabled/reactivated fence, LRU, no tombstones, strict wire types, failure locks execution");
